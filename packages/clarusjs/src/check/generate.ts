// .tscl → virtual TypeScript for type checking (it never runs). Template expressions are copied verbatim inside
// TypeScript that has the same meaning (@if → if, @for → for…of, a component → an object typed as its Inputs), and
// every copied span is recorded so tsc's errors can be mapped back to the template. Pure: string in, string out.
import { routeFromFile } from '../server/handler.ts'
import { parse, type Attr, type TemplateNode } from '../compiler/parse.ts'
import { splitImports } from '../compiler/script.ts'

/**
 * [virtual offset, length, source offset, exact]. Exact spans are verbatim copies (offsets map one to one); other
 * spans stand for a whole template construct and map to its start.
 */
export type Mapping = [number, number, number, boolean]

/**
 * `loader`: the module specifier of the page's .load.ts when it exports load(); what it returns is checked against
 * the page's inputs. `loaderSpan` is where that check sits in the generated code, so its errors can say so.
 */
export function generateTs(source: string, file: string, options: { loader?: string } = {}): { code: string; mappings: Mapping[]; loaderSpan?: [number, number] } {
  const parsed = parse(source, file)
  const mappings: Mapping[] = []
  let code = ''
  const emit = (text: string) => { code += text }
  const copy = (text: string, sourceStart: number) => { mappings.push([code.length, text.length, sourceStart, true]); code += text }
  const point = (text: string, sourceStart: number) => { mappings.push([code.length, text.length, sourceStart, false]); code += text }
  // Where a trimmed expression starts in the source, searching from `from`.
  const at = (text: string, from: number) => source.indexOf(text, from)
  const components = new Map(parsed.imports.map((imp) => [imp.name, imp]))
  const alias = (name: string) => `__cl_I_${name.replace(/-/g, '$')}`

  emit('// Generated by clarusjs for type checking. It never runs.\n')
  emit('declare function state<T>(value: T): T\n')
  emit('declare function derived<T>(fn: () => T): T\n')
  emit('declare function shared<T>(store: { get(): T }): T\n')
  emit('declare function __cl_use(value: unknown): void\n')
  emit('type __cl_Event<K extends string> = (K extends keyof HTMLElementEventMap ? HTMLElementEventMap[K] : Event) & { target: any; currentTarget: any }\n')
  for (const t of parsed.typeImports) {
    emit('import type ')
    copy(t.clause, t.clauseStart)
    emit(` from ${JSON.stringify(t.from)}\n`)
  }
  for (const imp of parsed.imports) emit(`import type { Inputs as ${alias(imp.name)}, Models as ${alias(imp.name)}_M } from ${JSON.stringify(`${imp.from}.ts`)}\n`)
  for (const d of parsed.dataImports) {
    emit('import ')
    copy(d.clause, d.clauseStart)
    emit(` from ${JSON.stringify(d.from)}\n`)
  }
  if (options.loader) emit(`import { load as __cl_load } from ${JSON.stringify(options.loader)}\n`)
  const script = parsed.script ? splitImports(parsed.script.code, file, source, parsed.script.start) : null
  if (parsed.script && script) {
    for (const imp of script.imports) {
      copy(imp.text, parsed.script.start + imp.start)
      emit('\n')
    }
  }

  // @type: local aliases (not exported: other files see them only through Inputs).
  for (const t of parsed.types) {
    emit(t.kind === 'interface' ? `interface ${t.name}${t.params ?? ''} ` : `type ${t.name}${t.params ?? ''} = `)
    copy(t.type, t.typeStart)
    emit('\n')
  }

  emit('\nexport interface Inputs {\n')
  // No inputs: one hidden optional member, so Inputs isn't an empty type (which accepts any props unchecked).
  if (!parsed.inputs.length) emit('  __cl_none?: never\n')
  for (const input of parsed.inputs) {
    emit('  ')
    copy(input.name, input.nameStart)
    emit(input.default !== undefined ? '?: ' : ': ')
    copy(input.type, input.typeStart)
    emit('\n')
  }
  emit('}\n')
  // The inputs a parent may bind two ways ([(name)]): this component's @model ones.
  const models = parsed.inputs.filter((i) => i.model).map((i) => JSON.stringify(i.name))
  emit(`export type Models = ${models.length ? models.join(' | ') : 'never'}\n`)
  let loaderSpan: [number, number] | undefined
  if (options.loader) {
    // Params and defaults fill the rest, so load() may return any subset of the inputs, each with the right type.
    // A Response (such as redirect()) is the answer instead of the page: only the rest is checked.
    emit('declare const __cl_loaded: Exclude<Awaited<ReturnType<typeof __cl_load>>, Response>\n')
    const start = code.length
    point('const __cl_from_load: Partial<Inputs> = __cl_loaded', 0)
    loaderSpan = [start, code.length]
    emit('\n')
  }
  // Inputs are read-only, all the way down: they belong to the parent (copy one into state() to change it here).
  emit('type __cl_Readonly<T> = T extends (...args: any[]) => unknown ? T : T extends object ? { readonly [K in keyof T]: __cl_Readonly<T[K]> } : T\n')
  emit('\nexport default function __cl_check(__cl_props: __cl_Readonly<Inputs>) {\n')
  // Inputs are constants; @model inputs may be written (the write goes to the parent), so they are `let`.
  for (const [keyword, list] of [['const', parsed.inputs.filter((x) => !x.model)], ['let', parsed.inputs.filter((x) => x.model)]] as const) {
    if (!list.length) continue
    emit(`  ${keyword} { `)
    list.forEach((input, i) => {
      if (i) emit(', ')
      copy(input.name, input.nameStart)
      if (input.default !== undefined && input.defaultStart !== undefined) {
        emit(' = ')
        copy(input.default, input.defaultStart)
      }
    })
    emit(' } = __cl_props\n')
  }
  if (parsed.script && script) {
    copy(script.body, parsed.script.start)
    emit('\n;\n') // the script may end without a semicolon; what follows must not continue its last statement
  }

  const use = (expr: string, start: number) => {
    emit('  __cl_use((')
    copy(expr, at(expr, start))
    emit('));\n')
  }
  const attrValueStart = (a: Attr) => a.start + a.name.length + (a.kind === 'static' || a.kind === 'interp' ? 2 : a.kind === 'model' ? 6 : 4)
  // [(x)]="path": the path must be assignable (a state variable or a property path; not a read-only input).
  const writable = (a: Attr & { expr: string }) => {
    emit('  ;(() => { (')
    copy(a.expr, at(a.expr, attrValueStart(a)))
    emit(') = (')
    copy(a.expr, at(a.expr, attrValueStart(a)))
    emit(') });\n')
  }

  function visit(node: TemplateNode): void {
    switch (node.type) {
      case 'text':
      case 'raw':
        return
      case 'expr':
        return use(node.expr, node.start + 2)
      case 'fill':
        node.children.forEach(visit)
        return
      case 'if':
        node.branches.forEach((b, i) => {
          if (b.cond === null) emit('  else {\n')
          else {
            emit(i === 0 ? '  if ((' : '  else if ((')
            copy(b.cond, at(b.cond, b.condStart))
            emit(')) {\n')
          }
          b.children.forEach(visit)
          emit('  }\n')
        })
        return
      case 'for': {
        emit('  for (const ')
        copy(node.item, node.itemStart)
        emit(' of ')
        copy(node.list, node.listStart)
        emit(') {\n    const $index: number = 0\n')
        if (node.track !== null) use(node.track, node.trackStart)
        node.children.forEach(visit)
        emit('  }\n')
        if (node.empty) {
          emit('  {\n')
          node.empty.forEach(visit)
          emit('  }\n')
        }
        return
      }
      case 'element': {
        const component = components.get(node.tag)
        if (component) {
          // An object literal typed as the child's Inputs: unknown props are excess properties, missing ones are
          // reported on the variable, which maps to the tag.
          emit('  { const ')
          point('__cl_p', node.start)
          emit(`: __cl_Readonly<${alias(node.tag)}> = { `) // a child reads its inputs only, so readonly values fit
          for (const a of node.attrs) {
            if (a.kind !== 'prop' && a.kind !== 'model') continue
            copy(a.name, a.start + (a.kind === 'model' ? 2 : 1))
            emit(': (')
            copy(a.expr, at(a.expr, attrValueStart(a)))
            emit('), ')
          }
          emit('}; __cl_use(__cl_p) }\n')
          for (const a of node.attrs) {
            if (a.kind !== 'model') continue
            // [(x)] needs @model x in the child.
            emit('  { const ')
            point('__cl_m', a.start + 2) // TypeScript reports a wrong initializer at the variable's name
            emit(`: ${alias(node.tag)}_M = ${JSON.stringify(a.name)}; __cl_use(__cl_m) }\n`)
            writable(a)
          }
          node.children.forEach(visit)
          return
        }
        for (const a of node.attrs) {
          if (a.kind === 'model') { use(a.expr, attrValueStart(a)); writable(a) }
          else if (a.kind === 'prop') use(a.expr, attrValueStart(a))
          else if (a.kind === 'interp') {
            for (const p of a.parts) if (typeof p !== 'string') use(p.expr, p.start + 2)
          } else if (a.kind === 'event') {
            emit(`  ;(($event: __cl_Event<${JSON.stringify(a.name)}>) => { `)
            copy(a.expr, at(a.expr, attrValueStart(a)))
            emit(' });\n')
          }
        }
        node.children.forEach(visit)
        return
      }
    }
  }
  parsed.nodes.forEach(visit)
  emit('}\n')
  return { code, mappings, loaderSpan }
}

/** The template offset for an offset in the virtual file, or null when it falls in generated scaffolding. */
export function toSourceOffset(mappings: Mapping[], virtualOffset: number): number | null {
  for (const [v, length, s, exact] of mappings) {
    if (virtualOffset >= v && virtualOffset < v + Math.max(length, 1)) return exact ? s + (virtualOffset - v) : s
  }
  return null
}

/** 'src/components' + '../domain/user' → 'src/domain/user' (POSIX, no fs). */
function joinPath(dir: string, rel: string): string {
  const out = dir.split('/').filter(Boolean)
  for (const part of rel.split('/')) {
    if (part === '..') out.pop()
    else if (part !== '.' && part !== '') out.push(part)
  }
  return out.join('/')
}

/**
 * .clarusjs/views.d.ts: view name → inputs, as declarations only, so an app's own tsconfig can include it. Each view's
 * inputs are written inline in a namespace; its `@import type`s become import() types with paths relative to
 * .clarusjs/ (where this file lives). Views that don't parse are left out (check reports them).
 */
export function viewsDeclaration(views: { file: string; source: string }[]): string {
  const lines = ['// Generated by clarusjs check: view name → inputs, for render() from clarusjs/views. Declarations only.']
  const entries: string[] = []
  views.forEach(({ file, source }, i) => {
    let parsed
    try { parsed = parse(source, file) } catch { return }
    const ns = `__cl_v${i}`
    const body: string[] = []
    for (const t of parsed.typeImports) {
      // Relative paths are written from .clarusjs/, one level below the project root.
      const from = t.from.startsWith('.') ? `../${joinPath(file.split('/').slice(0, -1).join('/'), t.from)}` : t.from
      const clause = t.clause.trim()
      if (clause.startsWith('{')) {
        for (const part of clause.slice(1, -1).split(',').map((p) => p.trim().replace(/^type\s+/, '')).filter(Boolean)) {
          const [name, local = name] = part.split(/\s+as\s+/).map((x) => x.trim())
          body.push(`  type ${local} = import(${JSON.stringify(from)}).${name}`)
        }
      } else if (!clause.startsWith('*')) {
        // ponytail: `* as N` type imports aren't carried into the registry; use named type imports for inputs.
        body.push(`  type ${clause} = import(${JSON.stringify(from)}).default`)
      }
    }
    // @type aliases stay inside this view's namespace.
    for (const t of parsed.types) body.push(t.kind === 'interface' ? `  interface ${t.name}${t.params ?? ''} ${t.type}` : `  type ${t.name}${t.params ?? ''} = ${t.type}`)
    body.push(`  interface Inputs {`)
    if (!parsed.inputs.length) body.push('    __cl_none?: never') // not empty: unknown props are errors
    for (const input of parsed.inputs) body.push(`    ${input.name}${input.default !== undefined ? '?' : ''}: ${input.type}`)
    body.push('  }')
    lines.push(`declare namespace ${ns} {`, ...body, '}')
    entries.push(`    ${JSON.stringify(file.replace(/^src\//, '').replace(/\.[^./]+$/, ''))}: ${ns}.Inputs`)
  })
  lines.push("declare module 'clarusjs/views' {", '  interface Views {', ...entries, '  }', '}', 'export {}', '')
  return lines.join('\n')
}

/**
 * .clarusjs/routes.d.ts: every page's route → its params, for href() from clarusjs/navigation. A page is any file
 * under src/pages but scripts (.ts/.js, so .load.ts too), styles and data, and _-prefixed files (partials). Markdown
 * and other page sources count, though check only type-checks .tscl pages (#142).
 */
export function routesDeclaration(files: string[]): string {
  // ponytail: page sources are recognised by what they aren't; a stray asset under src/pages would become a route.
  const pages = files.filter((f) => f.startsWith('src/pages/') && !/\.(m?[jt]s|css|json)$/.test(f) && !/(^|\/)_[^/]*$/.test(f))
  const routes = [...new Set(pages.map((f) => routeFromFile(`/${f}`)))].sort()
  const entries = routes.map((route) => {
    const keys = [...route.matchAll(/\[([^\]]+)\]/g)].map((m) => m[1]!)
    return `    ${JSON.stringify(route)}: ${keys.length ? `{ ${keys.map((k) => `${k}: string`).join('; ')} }` : '{}'}`
  })
  return ['// Generated by clarusjs check: every page route → its params, for href() from clarusjs/navigation.', "declare module 'clarusjs/navigation' {", '  interface Routes {', ...entries, '  }', '}', 'export {}', ''].join('\n')
}
